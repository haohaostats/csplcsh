test_that("prediction, decomposition and shifted covariates are consistent", {
  d <- example_data()
  fit <- cspl_fit(~ x + z, d)
  score <- cspl_score(fit, d)
  expect_equal(rowSums(score$components), score$score)
  d2 <- d; d2$x <- d2$x + 2; d2$z <- d2$z - 1
  expect_equal(cspl_score(cspl_fit(~ x + z, d2), d2)$score, score$score, tolerance = 1e-8)
  t <- c(0, .5, 2)
  S <- predict(fit, d[1:2, ], t)
  H <- predict(fit, d[1:2, ], t, type = "cumhaz")
  h <- predict(fit, d[1:2, ], t, type = "hazard")
  f <- predict(fit, d[1:2, ], t, type = "density")
  expect_equal(S, exp(-apply(H, c(1, 2), sum)))
  expect_equal(f, sweep(h, c(1, 2), S, "*"))
  expect_equal(dim(predict(fit, d[1, , drop = FALSE], 0)), c(1L, 1L))
  expect_error(predict(fit, d[1, , drop = FALSE], fit$tau + 1), "training")
  expect_equal(fit$fits[[1]]$method, "breslow")
})
test_that("named formulas and custom outcome columns work", {
  d <- example_data()
  a <- cspl_fit(list(`2` = ~ z, `1` = ~ x), d)
  b <- cspl_fit(list(~ x, ~ z), d)
  expect_equal(cspl_score(a, d)$score, cspl_score(b, d)$score)
  folds <- cspl_folds(d$status, 5)
  expected <- cspl_cv(~ x + z, d, folds)
  names(d)[1:2] <- c("follow up", "event code")
  actual <- cspl_cv(~ x + z, d, folds, time = "follow up", status = "event code")
  expect_equal(actual$scores, expected$scores)
})
test_that("invalid inputs fail clearly and truncation preserves endpoint events", {
  d <- example_data()
  expect_error(cspl_fit(~ x, transform(d, time = 0)), "positive")
  expect_error(cspl_fit(~ x, transform(d, status = factor(status))), "numeric")
  expect_error(cspl_fit(list(`1` = ~ x, `3` = ~ z), d), "cause codes")
  expect_error(cspl_fit(~ offset(x), d), "not supported")
  expect_error(cspl_cv(~ x, d, rep(1, nrow(d))), "two nonempty")
  expect_error(cspl_folds(d$status, 0), "nfold")
  out <- cspl_truncate(data.frame(time = c(1, 2, 3), status = c(1, 2, 1)), 2)
  expect_equal(out$status, c(1, 2, 0))
  expect_equal(out$time, c(1, 2, 2))
  expect_equal(attr(out, "n_truncated"), 1)
})
test_that("single-cause and intercept-only prediction retain dimensions", {
  d <- example_data(); d$status[d$status == 2] <- 0
  fit <- cspl_fit(~ 1, d)
  expect_equal(dim(predict(fit, d[1, , drop = FALSE], 0, type = "density")), c(1L, 1L, 1L))
  expect_true(all(is.finite(cspl_score(fit, d)$score)))
})
